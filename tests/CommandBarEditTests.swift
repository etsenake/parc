import AppKit

@main struct CommandBarEditTests {
    @MainActor static func main() {
        var count = 0
        func check(_ value: @autoclosure () -> Bool, _ message: String) {
            precondition(value(), message); count += 1
        }
        var state = CommandBarEditState(query: "weather")
        state.project(resultID: "native:1", text: "weather calgary")
        check(state.query == "weather", "arrow projection must not restart the provider")
        check(state.displayedText == "weather calgary", "real completion is displayed")
        check(state.selection == NSRange(location: 7, length: 8), "only added suffix is selected")
        state.accept()
        check(state.query == "weather", "Tab must not reinterpret the original request")
        check(state.displayedText == "weather calgary", "Tab keeps completion")
        check(state.selection == NSRange(location: 15, length: 0), "Tab accepts the suffix")
        state.project(resultID: "native:1", text: "weather calgary")
        check(state.selection.length == 0, "same publication projection retains acceptance")
        state.project(resultID: "native:2", text: "weather edmonton")
        check(state.query == "weather", "another row uses the original query")
        check(state.selection == NSRange(location: 7, length: 9), "another row gets its own suffix")
        state.clearProjection()
        check(state.displayedText == "weather", "command/tab/Space rows restore typed input")
        check(state.projection == nil, "a local action has no copied provider identity")
        state.project(resultID: "native:3", text: "weather radar")
        state.edit("weather rain")
        check(state.query == "weather rain" && state.projection == nil, "explicit editing starts a fresh query")
        state.project(resultID: "native:4", text: "")
        check(state.displayedText == "weather rain", "an empty provider completion cannot erase query")
        state.edit("WÉA")
        state.project(resultID: "case", text: "wéather")
        check(state.selection == NSRange(location: 3, length: 4), "case folding retains original UTF-16 range")
        state.edit("🌌")
        state.project(resultID: "emoji", text: "🌌 night")
        check(state.selection == NSRange(location: 2, length: 6), "surrogate pair is not split")
        state.edit("e\u{301}")
        state.project(resultID: "combining", text: "e\u{301} sky")
        check(state.selection == NSRange(location: 2, length: 4), "combining prefix keeps its complete range")
        state.edit("different")
        state.project(resultID: "url", text: "https://example.test/")
        check(state.selection == NSRange(location: 0, length: 21), "nonprefix completion selects the whole native edit text")
        state.edit("")
        state.project(resultID: "zero", text: "https://example.test/")
        check(state.selection.location == 0 && state.selection.length == 21, "zero-query completion is fully selected")
        state.edit("parc://set")
        state.project(resultID: "internal", text: "parc://settings/")
        check(state.selection == NSRange(location: 10, length: 6), "public internal scheme completion stays public")

        // Exercise the real NSTextView UTF-16 replacement/caret contract. This
        // is an inert local editor component, never a browser or URL load.
        let editor = NSTextView(frame: NSRect(x: 0, y: 0, width: 400, height: 40))
        editor.isRichText = false
        state.edit("🌌"); state.project(resultID: "native", text: "🌌 night")
        editor.string = state.displayedText; editor.setSelectedRange(state.selection)
        editor.insertText(" dawn", replacementRange: editor.selectedRange())
        check(editor.string == "🌌 dawn", "typing replaces only the selected completion")
        state.edit(editor.string)
        check(state.query == "🌌 dawn", "real editing commits its actual text")
        state.project(resultID: "native", text: "🌌 dawn sky")
        editor.string = state.displayedText; editor.setSelectedRange(state.selection)
        state.accept(); editor.setSelectedRange(state.selection)
        editor.insertText("!", replacementRange: editor.selectedRange())
        check(editor.string == "🌌 dawn sky!", "typing after Tab appends to accepted text")
        state.edit("weather"); state.project(resultID: "native", text: "weather calgary")
        editor.string = state.displayedText; editor.setSelectedRange(state.selection)
        editor.deleteBackward(nil)
        check(editor.string == "weather", "Backspace removes the completion without deleting the typed prefix")
        state.edit(editor.string)
        check(state.projection == nil && state.query == "weather", "Backspace remains ordinary editing")
        state.project(resultID: "stale", text: "weather today"); state.clearProjection()
        editor.string = state.displayedText; editor.setSelectedRange(state.selection)
        check(editor.string == "weather" && editor.selectedRange().length == 0, "disappearing result restores query and caret")
        // Automatic completion uses the same real field editor, but captures
        // the editing cause and current range before each provider publication.
        state = CommandBarEditState(query: "")
        check(!state.allowsInlineCompletion, "initial address restoration is not typed input")
        state.userEdit("arc.n", selection: NSRange(location: 5, length: 0), hasMarkedText: false, didBackspace: false)
        check(state.allowsInlineCompletion, "typing at end admits the native default suffix")
        check(state.projectInline(resultID: "default", text: "arc.net/release-notes", selection: NSRange(location: 5, length: 0), hasMarkedText: false), "actual default projection is accepted")
        check(state.query == "arc.n" && state.projection?.automatic == true, "automatic display preserves producer query")
        editor.string = state.displayedText; editor.setSelectedRange(state.selection)
        check(editor.selectedRange() == NSRange(location: 5, length: 16), "provider suffix uses native UTF-16 selection")
        editor.deleteBackward(nil)
        state.userEdit(editor.string, selection: editor.selectedRange(), hasMarkedText: false, didBackspace: true)
        check(editor.string == "arc.n" && !state.allowsInlineCompletion, "Backspace keeps literal prefix and suppresses this publication")
        check(!state.projectInline(resultID: "late", text: "arc.net/release-notes", selection: editor.selectedRange(), hasMarkedText: false), "late result cannot restore deleted suffix")
        editor.insertText("e", replacementRange: editor.selectedRange())
        state.userEdit(editor.string, selection: editor.selectedRange(), hasMarkedText: false, didBackspace: false)
        check(state.projectInline(resultID: "new", text: "arc.net/release-notes", selection: editor.selectedRange(), hasMarkedText: false), "further typed character resumes real completion")
        editor.string = state.displayedText; editor.setSelectedRange(NSRange(location: 2, length: 0))
        check(!state.projectInline(resultID: "other", text: "arc.net/other", selection: editor.selectedRange(), hasMarkedText: false), "late publication cannot overwrite a mid-string caret")
        state.stopAutomaticCompletion()
        check(!state.projectInline(resultID: "other", text: "arc.net/other", selection: NSRange(location: editor.string.utf16.count, length: 0), hasMarkedText: false), "explicit caret/result intent stays suppressed")
        state.edit("")
        state.userEdit("🌌", selection: NSRange(location: 2, length: 0), hasMarkedText: false, didBackspace: false)
        check(state.projectInline(resultID: "unicode", text: "🌌 sky", selection: NSRange(location: 2, length: 0), hasMarkedText: false), "surrogate-aware automatic suffix")
        check(state.selection == NSRange(location: 2, length: 4), "automatic suffix never splits surrogate")
        state.accept()
        check(!state.projectInline(resultID: "unicode2", text: "🌌 stars", selection: NSRange(location: 6, length: 0), hasMarkedText: false), "Tab acceptance is not replaced automatically")
        state.edit("")
        state.userEdit("日本", selection: NSRange(location: 2, length: 0), hasMarkedText: true, didBackspace: false)
        check(!state.allowsInlineCompletion, "composition cannot request automatic edits")
        state.edit("")
        state.userEdit("a", selection: NSRange(location: 1, length: 0), hasMarkedText: false, didBackspace: false)
        check(!state.projectInline(resultID: "IME", text: "arc", selection: NSRange(location: 1, length: 0), hasMarkedText: true), "composition beginning after query blocks delivery")
        check(!state.projectInline(resultID: "wrong", text: "weather", selection: NSRange(location: 1, length: 0), hasMarkedText: false), "automatic nonprefix text cannot replace input")
        check(!state.projectInline(resultID: "same", text: "a", selection: NSRange(location: 1, length: 0), hasMarkedText: false), "empty suffix does not create a projection")
        state.userEdit("ar", selection: NSRange(location: 1, length: 0), hasMarkedText: false, didBackspace: false)
        check(!state.allowsInlineCompletion, "mid-string user edit suppresses provider inline ranking")
        state.edit("abcdef")
        state.userEdit("abc", selection: NSRange(location: 3, length: 0), hasMarkedText: false, didBackspace: true)
        check(!state.allowsInlineCompletion, "non-keyboard deletion is suppressed too")
        state.edit("a")
        state.userEdit("ar", selection: NSRange(location: NSNotFound, length: 0), hasMarkedText: false, didBackspace: false)
        check(!state.allowsInlineCompletion, "missing editor has no automatic completion owner")
        check(!CommandBarEditState.reachesEnd(NSRange(location: 1, length: Int.max), of: "a"), "invalid ranges cannot overflow")
        check(CommandBarEditState.reachesEnd(NSRange(location: 1, length: 2), of: "arc"), "existing selected suffix reaches the end")
        // Observe AppKit's actual text-storage edit records: selection replacement
        // may shorten text while still inserting, unlike deletion of a suffix.
        final class Changes: @unchecked Sendable { var deletion = false; var calls = 0 }
        let changes = Changes()
        let storage = editor.textStorage!
        let token = NotificationCenter.default.addObserver(forName: NSTextStorage.didProcessEditingNotification, object: storage, queue: .main) { notification in
            MainActor.assumeIsolated {
                guard let text = notification.object as? NSTextStorage, text.editedMask.contains(.editedCharacters) else { return }
                changes.deletion = CommandBarEditState.deletesCharacters(editedRange: text.editedRange, changeInLength: text.changeInLength)
                changes.calls += 1
            }
        }
        editor.string = "arc.net/release-notes"; editor.setSelectedRange(NSRange(location: 5, length: 16))
        editor.deleteBackward(nil)
        check(changes.deletion, "actual suffix deletion is identified from native storage")
        state.userEdit(editor.string, selection: editor.selectedRange(), hasMarkedText: false, didBackspace: changes.deletion)
        check(!state.allowsInlineCompletion, "actual native deletion suppresses next query")
        editor.insertText("e", replacementRange: editor.selectedRange())
        check(!changes.deletion, "actual inserted character clears deletion status")
        editor.setSelectedRange(NSRange(location: 0, length: editor.string.utf16.count))
        editor.insertText("a", replacementRange: editor.selectedRange())
        check(!changes.deletion, "shorter replacement of a selected address is still an insertion")
        state.userEdit(editor.string, selection: editor.selectedRange(), hasMarkedText: false, didBackspace: changes.deletion)
        check(state.allowsInlineCompletion, "shorter replacement can complete immediately")
        check(changes.calls >= 3, "real text-storage observer covers each native edit")
        NotificationCenter.default.removeObserver(token)
        print("\(count) command-bar editing assertions passed")
    }
}
