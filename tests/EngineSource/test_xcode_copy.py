import copy
import os
import plistlib
import re
import subprocess
import unittest
from unittest.mock import patch

import test_engine_source as fixture

engine = fixture.engine
ENSURE_XCODE = engine.ensure_xcode
COMPLETE_XCODE = engine.complete_xcode
SDK = "Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX27.2.sdk"
BIN = "Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/bin"
SETTINGS = ' use_system_xcode=false use_autogenerated_modules=false mac_sdk_official_version="27.2"'
REFERENCE = "../../build/mac_files/xcode_binaries/" + BIN


class XcodeCopyTests(unittest.TestCase):
    def setUp(self):
        fixture.EngineSourceTests.setUp(self)
        self.lock = copy.deepcopy(self.lock)
        defines = re.sub(r'\s*(use_system_xcode|use_autogenerated_modules|mac_sdk_official_version|'
                         r'mac_sdk_official_build_version|mac_sdk_path)=("[^"]*"|true|false)', "",
                         self.lock["build"]["gn_defines"])
        self.without = defines
        self.lock["build"]["gn_defines"] = defines + SETTINGS
        (self.workspace / "chromium/src").mkdir(parents=True)
        self.xcode = self.base / "Xcode.app/Contents"
        (self.xcode / "version.plist").parent.mkdir(parents=True)
        (self.xcode / "version.plist").write_bytes(plistlib.dumps({"CFBundleShortVersionString": "27.2",
                                                                   "ProductBuildVersion": "27B52"}))
        self.installed = self.xcode / SDK.removeprefix("Contents/")
        (self.installed / "usr/include").mkdir(parents=True)
        (self.installed / "System/Library/CoreServices").mkdir(parents=True)
        (self.installed / "SDKSettings.json").write_text('{"Version": "27.2"}')
        self.write_sdk_version("27.2")
        self.header = self.installed / "usr/include/stdio.h"
        self.header.write_text("int printf();")
        os.utime(self.header, ns=(1_700_000_000_000_000_000, 1_700_000_000_000_000_000))
        tools = self.xcode / BIN.removeprefix("Contents/")
        tools.mkdir(parents=True)
        (tools / "gperf").write_text("gperf")
        os.utime(tools / "gperf", ns=(1_600_000_000_000_000_000, 1_600_000_000_000_000_000))
        (tools.parent / "libexec").mkdir()
        (tools.parent / "libexec/migcom").write_text("migcom")
        self.metal = self.base / "cryptex/Metal.xctoolchain"
        (self.metal / "usr/bin").mkdir(parents=True)
        (self.metal / "usr/metal/32023/bin").mkdir(parents=True)
        (self.metal / "usr/bin/metal").write_text("metal launcher")
        (self.metal / "usr/metal/32023/bin/metal").write_text("metal compiler")
        self.output = self.workspace / "chromium/src/out/ParcDistribution_GN_arm64"
        self.output.mkdir(parents=True)
        self.calls = []
        self.downloadable = True
        self.downloaded = False
        self.linked = {}
        self.addCleanup(subprocess.run, ["/bin/chmod", "-R", "u+w", str(self.base)])

    def write_sdk_version(self, version):
        plist = self.installed / "System/Library/CoreServices/SystemVersion.plist"
        plist.write_bytes(plistlib.dumps({"ProductVersion": version, "ProductBuildVersion": "26B118"}))

    def write_build(self, *tools, stale=()):
        lines = [f"rule r\n  command = tool {REFERENCE}/{tool}\n" for tool in tools if "/" not in tool]
        (self.output / "obj").mkdir(exist_ok=True)
        (self.output / "obj/live.ninja").write_text("".join(f"  command = {REFERENCE}/{tool}\n"
                                                           for tool in tools if "/" in tool))
        (self.output / "obj/stale.ninja").write_text("".join(f"  command = {REFERENCE}/{tool}\n" for tool in stale))
        (self.output / "toolchain.ninja").write_text("".join(lines) + "subninja obj/live.ninja\n")
        (self.output / "build.ninja").write_text("subninja toolchain.ninja\n")

    def run_with_xcode(self, action, sdk=None):
        real = subprocess.run
        found = str(self.installed if sdk is None else sdk)

        def run(argv, *args, **kwargs):
            self.calls.append(argv)
            if argv[0] == "/usr/bin/xcrun" and argv[1] == "--find":
                if argv[2] == "metal" and self.downloaded:
                    return subprocess.CompletedProcess(argv, 0, str(self.metal / "usr/bin/metal") + "\n", "")
                return subprocess.CompletedProcess(argv, 1, "", "not found")
            if argv[0] == "/usr/bin/xcrun":
                return subprocess.CompletedProcess(argv, 0, found + "\n", "")
            if argv[0] == "/usr/bin/xcode-select":
                return subprocess.CompletedProcess(argv, 0, str(self.xcode / "Developer") + "\n", "")
            if argv[0] == "/usr/bin/xcodebuild":
                self.downloaded = self.downloadable
                return subprocess.CompletedProcess(argv, 0, "", "")
            if argv[0] == "/usr/bin/otool":
                return subprocess.CompletedProcess(argv, 0, argv[2] + ":\n" + self.linked.get(Path(argv[2]).name, ""), "")
            return real(argv, *args, **kwargs)

        with patch.object(engine.subprocess, "run", side_effect=run):
            return action()

    def ensure(self, sdk=None):
        return self.run_with_xcode(lambda: ENSURE_XCODE(self.workspace, self.lock), sdk)

    def complete(self):
        return self.run_with_xcode(lambda: COMPLETE_XCODE(self.workspace, self.lock, self.output))

    def test_the_version_and_sdk_are_copied_into_the_engine_with_their_dates(self):
        folder = self.ensure()
        self.assertEqual(folder, self.workspace / "chromium/src" / engine.XCODE_FOLDER)
        version = plistlib.loads((folder / "Contents/version.plist").read_bytes())
        self.assertEqual(version["ProductBuildVersion"], "27B52")
        self.assertEqual((folder / SDK / "usr/include/stdio.h").read_text(), "int printf();")
        self.assertEqual((folder / SDK / "usr/include/stdio.h").stat().st_mtime_ns, 1_700_000_000_000_000_000)
        self.assertFalse(folder.with_name(folder.name + ".copying").exists())

    def test_an_existing_folder_is_never_touched_again(self):
        folder = self.ensure()
        os.utime(self.header, ns=(1_800_000_000_000_000_000, 1_800_000_000_000_000_000))
        self.calls.clear()
        self.assertEqual(self.ensure(), folder)
        self.assertEqual(self.calls, [])
        self.assertEqual((folder / SDK / "usr/include/stdio.h").stat().st_mtime_ns, 1_700_000_000_000_000_000)

    def test_a_new_folder_is_read_only_so_no_build_step_can_change_it(self):
        folder = self.ensure()
        self.assertFalse(os.access(folder, os.W_OK))
        self.assertFalse(os.access(folder / SDK / "usr/include", os.W_OK))

    def test_an_engine_without_the_setting_keeps_using_the_installed_xcode(self):
        self.lock["build"]["gn_defines"] = self.without
        self.write_build("gperf")
        self.assertIsNone(self.ensure())
        self.assertEqual(self.complete(), [])
        self.assertFalse((self.workspace / "chromium/src/build/mac_files").exists())

    def test_a_missing_installed_sdk_says_what_to_install(self):
        with self.assertRaisesRegex(engine.Refusal, "install Xcode"):
            self.ensure(self.base / "nowhere")

    def test_an_installed_sdk_other_than_the_pinned_one_is_refused(self):
        self.write_sdk_version("27.3")
        with self.assertRaisesRegex(engine.Refusal, "pins macOS SDK 27.2 but the installed Xcode has 27.3"):
            self.ensure()
        self.assertFalse((self.workspace / "chromium/src" / engine.XCODE_FOLDER).exists())

    def test_an_incomplete_folder_is_refused_rather_than_patched(self):
        (self.workspace / "chromium/src" / engine.XCODE_FOLDER / "Contents").mkdir(parents=True)
        with self.assertRaisesRegex(engine.Refusal, "incomplete"):
            self.ensure()

    def test_every_tool_the_generated_build_names_is_copied_from_xcode_with_its_date(self):
        folder = self.ensure()
        self.write_build("gperf", "../libexec/migcom", stale=["stale-tool"])
        copied = self.complete()
        self.assertEqual(copied, [BIN + "/gperf", BIN.removesuffix("/bin") + "/libexec/migcom"])
        self.assertEqual((folder / BIN / "gperf").read_text(), "gperf")
        self.assertEqual((folder / BIN / "gperf").stat().st_mtime_ns, 1_600_000_000_000_000_000)
        self.assertEqual((folder / BIN / "../libexec/migcom").read_text(), "migcom")
        self.assertFalse((folder / BIN / "stale-tool").exists())
        self.assertFalse(os.access(folder / BIN, os.W_OK))

    def test_nothing_is_done_once_every_named_tool_is_on_the_drive(self):
        self.ensure()
        self.write_build("gperf")
        self.complete()
        self.calls.clear()
        self.assertEqual(self.complete(), [])
        self.assertEqual(self.calls, [])

    def test_a_tool_from_another_apple_toolchain_brings_that_toolchain_and_links_it(self):
        folder = self.ensure()
        self.downloaded = True
        self.write_build("metal")
        self.complete()
        link = folder / BIN / "metal"
        self.assertTrue(link.is_symlink())
        self.assertFalse(os.path.isabs(os.readlink(link)))
        self.assertEqual(link.read_text(), "metal launcher")
        copied = folder / "Contents/Developer/Toolchains/Metal.xctoolchain"
        self.assertEqual(link.resolve(), (copied / "usr/bin/metal").resolve())
        self.assertEqual((copied / "usr/metal/32023/bin/metal").read_text(), "metal compiler")
        self.assertNotIn(["/usr/bin/xcodebuild", "-downloadComponent", "MetalToolchain"], self.calls)

    def test_a_tool_apple_ships_as_a_download_is_downloaded_on_this_mac_first(self):
        folder = self.ensure()
        self.write_build("metal")
        self.complete()
        self.assertIn(["/usr/bin/xcodebuild", "-downloadComponent", "MetalToolchain"], self.calls)
        self.assertEqual((folder / BIN / "metal").read_text(), "metal launcher")

    def test_a_tool_nobody_can_supply_stops_before_compiling_and_names_it(self):
        folder = self.ensure()
        self.downloadable = False
        self.write_build("metallib")
        with self.assertRaisesRegex(engine.Refusal, "needs Xcode's metallib"):
            self.complete()
        self.assertIn(["/usr/bin/xcodebuild", "-downloadComponent", "MetalToolchain"], self.calls)
        self.write_build("unknown-tool")
        self.calls.clear()
        with self.assertRaisesRegex(engine.Refusal, "needs Xcode's unknown-tool"):
            self.complete()
        self.assertNotIn("/usr/bin/xcodebuild", [call[0] for call in self.calls])
        self.assertFalse(os.access(folder / "Contents", os.W_OK))

    def test_a_tool_that_loads_libraries_beside_it_is_refused_rather_than_copied_broken(self):
        folder = self.ensure()
        self.linked["gperf"] = "\t@rpath/libgperf.dylib (compatibility version 1.0.0)\n"
        self.write_build("gperf")
        with self.assertRaisesRegex(engine.Refusal, "loads libraries next to it"):
            self.complete()
        self.assertFalse((folder / BIN / "gperf").exists())

    def test_both_build_folders_get_the_settings_unchanged_and_no_sdk_path(self):
        development = engine.engine_arguments(self.lock, self.lock["build"]["gn_defines"] + " symbol_level=0")
        shipping = engine.shipping_arguments(self.workspace, engine.shipping_environment(self.workspace, self.lock, 0),
                                             self.lock)
        for arguments in (development, shipping):
            self.assertIn(b"use_system_xcode=false\n", arguments)
            self.assertIn(b'mac_sdk_official_version="27.2"\n', arguments)
            self.assertNotIn(b"mac_sdk_path", arguments)

    def test_the_folder_is_where_chromium_looks_and_its_ignore_rules_keep_it(self):
        self.assertEqual(engine.XCODE_FOLDER, "build/mac_files/xcode_binaries")


Path = engine.Path

if __name__ == "__main__":
    unittest.main()
