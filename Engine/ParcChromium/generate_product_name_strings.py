#!/usr/bin/env python3
"""Generate Parc's localized product-name overrides from Chromium's GRIT data."""

import argparse
import importlib.util
import os
from pathlib import Path
import re
import sys


class MacDefines(dict):
    """The release's macOS defines, with every unlisted define false."""

    def __init__(self, names):
        super().__init__(dict.fromkeys(names, True), safe_browsing_mode=1,
                         _google_chrome=False)

    def __contains__(self, name):
        return True

    def __missing__(self, name):
        return False


def _cpp_string(value):
    result = []
    for character in value:
        codepoint = ord(character)
        if character == '\\':
            result.append('\\\\')
        elif character == '"':
            result.append('\\"')
        elif character == '\n':
            result.append('\\n')
        elif character == '\r':
            result.append('\\r')
        elif character == '\t':
            result.append('\\t')
        elif character == '?':
            result.append('\\?')
        elif 0x20 <= codepoint <= 0x7E:
            result.append(character)
        elif codepoint <= 0xFFFF:
            result.append(f'\\u{codepoint:04X}')
        else:
            result.append(f'\\U{codepoint:08X}')
    return 'u"' + ''.join(result) + '"'


def _symbol(locale):
    return 'k_' + re.sub(r'[^A-Za-z0-9]', '_', locale)


def _load_branding(path):
    spec = importlib.util.spec_from_file_location('parc_branding', path)
    branding = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(branding)
    return branding


def _unbranded_translation(node, language, gender, message_module):
    text = node.clique.MessageForLanguageAndGender(
        language, gender, node.PseudoIsAllowed(),
        node.ShouldFallbackToEnglish()).GetRealContent()
    if node._replace_ellipsis and '...' in text:
        text = message_module._ELLIPSIS_PATTERN.sub(
            message_module._ELLIPSIS_SYMBOL, text)
    return text.replace('\ufeff', '').replace('[GRITLANGCODE]', language)


def collect_overrides(source_root, locales, branding_path, resource_ids_path):
    """Return {locale: {numeric id: branded text}} and parsed roots."""
    sys.path.insert(0, str(source_root / 'tools/grit'))
    from grit import constants, grd_reader
    from grit.node import message

    branding = _load_branding(branding_path)
    defines = MacDefines(branding.MAC_DEFINES)
    overrides = {locale: {} for locale in locales}
    origins = {locale: {} for locale in locales}
    roots = []
    for relative in branding.RESOURCE_STRING_GRDS:
        path = source_root / relative
        root = grd_reader.Parse(
            str(path), defines=defines, first_ids_file=str(resource_ids_path),
            target_platform='darwin', translate_genders=True)
        root.SetOutputLanguage('en')
        root.RunGatherers()
        root.InitializeIds()
        id_map = root.GetIdMap()
        for node in root.ActiveDescendants():
            if not isinstance(node, message.MessageNode) or not node.clique:
                continue
            resource_id = id_map[node.GetTextualIds()[0]]
            for locale in locales:
                branded = (node.ws_at_start +
                           branding.Translate(
                               node, locale, constants.DEFAULT_GENDER) +
                           node.ws_at_end)
                original = (
                    node.ws_at_start +
                    _unbranded_translation(
                        node, locale, constants.DEFAULT_GENDER, message) +
                    node.ws_at_end)
                if branded == original:
                    continue
                previous = overrides[locale].setdefault(resource_id, branded)
                origin = origins[locale].setdefault(
                    resource_id, f'{relative}:{node.NameOrOffset()}')
                if previous != branded:
                    raise ValueError(
                        f'conflicting product-name resource {resource_id}: '
                        f'{origin} and {relative}:{node.NameOrOffset()}')
        roots.append((path, root))
    return overrides, roots


def _write_header(path):
    path.write_text(
        '// Generated by //parc:product_name_strings. Do not edit.\n'
        '#ifndef PARC_PRODUCT_NAME_STRINGS_H_\n'
        '#define PARC_PRODUCT_NAME_STRINGS_H_\n'
        '#include <string>\n'
        '#include <string_view>\n'
        'namespace parc {\n'
        'bool GetProductNameString(std::string_view locale, int message_id,\n'
        '                          std::u16string* value);\n'
        '}  // namespace parc\n'
        '#endif  // PARC_PRODUCT_NAME_STRINGS_H_\n')


def _locale_conditions(locale):
    names = {locale, locale.replace('-', '_')}
    if locale == 'en-US':
        names.add('en')
    if locale == 'nb':
        names.add('no')
    return ' || '.join(f'locale == "{name}"' for name in sorted(names))


def _write_source(path, overrides):
    lines = [
        '// Generated by //parc:product_name_strings. Do not edit.',
        '#include "parc/product_name_strings.h"',
        '',
        '#include <algorithm>',
        '#include <cstddef>',
        '#include <iterator>',
        '',
        'namespace parc {',
        'namespace {',
        'struct Entry {',
        '  int id;',
        '  const char16_t* value;',
        '};',
    ]
    populated = [(locale, entries) for locale, entries in overrides.items()
                 if entries]
    for locale, entries in populated:
        lines.append(f'constexpr Entry {_symbol(locale)}[] = {{')
        for resource_id, value in sorted(entries.items()):
            lines.append(f'  {{{resource_id}, {_cpp_string(value)}}},')
        lines.append('};')
    lines.extend([
        'struct Entries {',
        '  const Entry* data;',
        '  std::size_t size;',
        '};',
        'Entries EntriesForLocale(std::string_view locale) {',
    ])
    for index, (locale, _) in enumerate(populated):
        prefix = 'if' if index == 0 else 'else if'
        symbol = _symbol(locale)
        lines.extend([
            f'  {prefix} ({_locale_conditions(locale)}) {{',
            f'    return {{{symbol}, std::size({symbol})}};',
            '  }',
        ])
    lines.extend([
        '  const std::size_t separator = locale.find_first_of("-_");',
        '  if (separator != std::string_view::npos) {',
        '    return EntriesForLocale(locale.substr(0, separator));',
        '  }',
        '  return {nullptr, 0};',
        '}',
        '}  // namespace',
        '',
        'bool GetProductNameString(std::string_view locale, int message_id,',
        '                          std::u16string* value) {',
        '  const Entries entries = EntriesForLocale(locale);',
        '  if (!entries.data) {',
        '    return false;',
        '  }',
        '  const auto found = std::lower_bound(',
        '      entries.data, entries.data + entries.size, message_id,',
        '      [](const Entry& entry, int id) { return entry.id < id; });',
        '  if (found == entries.data + entries.size || found->id != message_id) {',
        '    return false;',
        '  }',
        '  *value = found->value;',
        '  return true;',
        '}',
        '',
        '}  // namespace parc',
        '',
    ])
    path.write_text('\n'.join(lines))


def _write_depfile(path, outputs, source_root, branding_path,
                   resource_ids_path, roots):
    sys.path.insert(0, str(source_root / 'build'))
    sys.path.insert(0, str(source_root / 'tools/grit'))
    import action_helpers
    import grit_info

    branding = _load_branding(branding_path)
    defines = MacDefines(branding.MAC_DEFINES)
    ids = str(resource_ids_path)
    cwd = Path.cwd()
    dependencies = {
        os.path.relpath(Path(__file__).resolve(), cwd),
        os.path.relpath(branding_path.resolve(), cwd),
        os.path.relpath(resource_ids_path.resolve(), cwd),
    }
    for grd, _ in roots:
        dependencies.add(os.path.relpath(grd.resolve(), cwd))
        dependencies.update(grit_info.Inputs(
            str(grd), defines, ids, target_platform='darwin'))
    action_helpers.write_depfile(
        str(path), str(outputs[0]), tuple(dependencies))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-root', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--depfile', type=Path, required=True)
    parser.add_argument('--branding', type=Path, required=True)
    parser.add_argument('--resource-ids', type=Path, required=True)
    parser.add_argument('--locale', action='append', dest='locales',
                        required=True)
    args = parser.parse_args()
    source_root = args.source_root.resolve()
    branding_path = args.branding.resolve()
    resource_ids_path = args.resource_ids.resolve()
    overrides, roots = collect_overrides(
        source_root, args.locales, branding_path, resource_ids_path)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.source.parent.mkdir(parents=True, exist_ok=True)
    _write_header(args.header)
    _write_source(args.source, overrides)
    _write_depfile(args.depfile, (args.header, args.source), source_root,
                   branding_path, resource_ids_path, roots)


if __name__ == '__main__':
    main()
